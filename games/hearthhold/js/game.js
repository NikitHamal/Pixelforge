  function pick(t) {
    if (!t || !W.inb(t.x, t.y)) { S.sel = null; showInspect(null); return; }
    let best = null, bd = 1.1;
    for (const v of S.folk) {
      const d = Math.hypot(v.x - t.x, v.y - t.y);
      if (d < bd) { bd = d; best = { kind: 'folk', ref: v }; }
    }
    if (!best) {
      const b = findStructure(t.x, t.y);
      if (b) best = { kind: 'build', ref: b };
    }
    S.sel = best;
    showInspect(best);
    if (best) SFX.pick();
  }

  /* The map edge is a hard stop: letting the camera drift past it puts a band
     of dead black on screen, which reads as a rendering bug rather than as the
     edge of the world. When the viewport is wider than the map, centre it. */
  function clampCam() {
    const vw = cv.width / S.zoom, vh = cv.height / S.zoom;
    const mx = MW * T - vw, my = MH * T - vh;
    S.cam.x = mx <= 0 ? mx / 2 : clamp(S.cam.x, 0, mx);
    S.cam.y = my <= 0 ? my / 2 : clamp(S.cam.y, 0, my);
  }

  let sized = false;
