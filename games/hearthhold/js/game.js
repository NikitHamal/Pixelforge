  function refreshPalette() {
    el.palette.innerHTML = '';
    paletteCells.length = 0;
    for (const c of CATS) c._btn.classList.toggle('on', c.id === S.cat);
    for (const def of BUILD) {
      if (def.cat !== S.cat) continue;
      const cell = mk('button', 'cell', el.palette);
      const ic = mk('canvas', null, cell);
      ic.width = 32; ic.height = 32;
      drawPaletteIcon(ic, def);
      mk('em', null, cell, def.name);
      cell.addEventListener('click', () => {
        S.tool = S.tool === def ? null : def;
        S.sel = null;
        SFX.pick();
        refreshPalette();
        showCard(S.tool);
      });
      cell.addEventListener('mouseenter', () => showCard(def));
      cell.addEventListener('mouseleave', () => showCard(S.tool));
      cell._def = def;
      paletteCells.push(cell);
    }
    syncPalette();
  }

  /* Affordability is re-read every frame rather than on spend, because the
     stockpile also moves on its own — a hauler arriving can make something
     affordable with no click involved. */
  function syncPalette() {
    for (const cell of paletteCells) {
      const d = cell._def;
      cell.classList.toggle('on', S.tool === d);
      cell.classList.toggle('poor', !d.demolish && !has(d.cost));
    }
  }

  function drawPaletteIcon(icv, def) {
    const g = icv.getContext('2d');
    g.imageSmoothingEnabled = false;
    if (def.spr) {
      const f = sprFrame(def.spr[0], def.spr[1], 0);
      if (f) g.drawImage(f.cv, 0, 0);
      return;
    }
    if (def.wall) {
      const sheet = def.wall === 2 ? ART.rampart : ART.palisade;
      if (sheet && sheet[10]) { g.drawImage(sheet[10], 0, 8); g.drawImage(sheet[10], 16, 8); }
      return;
    }
    if (def.ground !== undefined && ART.ground) { g.drawImage(ART.ground[def.ground], 8, 8); return; }
    if (def.field) {
      const f = sprFrame('farm_crops', def.field === 'herb' ? 'carrot3' : 'wheat4', 0);
      if (f) g.drawImage(f.cv, 0, 0);
      return;
    }
    if (def.demolish) {
      const f = sprFrame('hold_site', 'ruin', 0);
      if (f) g.drawImage(f.cv, 0, 0);
    }
  }

